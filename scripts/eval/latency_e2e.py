#!/usr/bin/env python3
"""
R2 comment 1b: end-to-end inference latency of the completion module, not just the
network forward pass. Times, at batch size 1, the stages a deployed system runs per
map: input preprocessing (normalise + pad + host->device), network forward
(beta-NLL), uncertainty, and output composition (denormalise + blend measured cells
+ device->host). The upstream point-cloud rasterisation is a shared elevation-mapping
front-end and is not attributed to the completion network; embedded hardware was not
available, so numbers are on the local GPU.

    python tools/latency_e2e.py --iters 100

Outputs to runs/experiments_review/r2c1b_latency_e2e/:
  latency.json, table_latency.tex
"""
import argparse
import json
import sys
from pathlib import Path
import numpy as np
import torch

from elevcomp.paths import project_root, reports_dir
from elevcomp.inference import nll_predict
from elevcomp.model import build_model

ROOT = project_root()

RUN = None   # resolved in main(); override with --exp_dir
OUT = reports_dir() / 'latency'
DEV = torch.device('cuda' if torch.cuda.is_available() else 'cpu')


def sync():
    if DEV.type == 'cuda':
        torch.cuda.synchronize()


def timed(fn, iters, warmup):
    for _ in range(warmup):
        fn()
    sync()
    ts = []
    for _ in range(iters):
        sync(); t0 = torch.cuda.Event(enable_timing=True) if DEV.type == 'cuda' else None
        if t0 is not None:
            t1 = torch.cuda.Event(enable_timing=True)
            t0.record(); fn(); t1.record(); sync()
            ts.append(t0.elapsed_time(t1))
        else:
            import time as _t
            s = _t.perf_counter(); fn(); ts.append((_t.perf_counter() - s) * 1e3)
    return float(np.median(ts))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--iters', type=int, default=100)
    ap.add_argument('--warmup', type=int, default=20)
    ap.add_argument('--exp_dir', default=None,
                    help='cross-validation experiment directory '
                         '(default: $ELEVCOMP_EXPERIMENT or newest runs/cv_*)')
    args = ap.parse_args()

    global RUN
    RUN = Path(args.exp_dir).expanduser().resolve() if args.exp_dir else default_experiment()
    OUT.mkdir(parents=True, exist_ok=True)

    fold = sorted(RUN.glob('fold_*'))[0]
    ck = torch.load(fold / 'best.pth', map_location=DEV)
    cfg, stats = ck['config'], ck['stats']
    mean, std = stats['mean'], stats['std']
    pad = cfg['pad_to']; H0 = 251; ph = (pad - H0) // 2
    model = build_model(cfg).to(DEV).eval()
    model.load_state_dict(ck['model'])
    gpu = torch.cuda.get_device_name(0) if DEV.type == 'cuda' else 'CPU'

    # a raw partial map (numpy, metres) + mask, as a deployed front-end would hand over
    rng = np.random.default_rng(0)
    pe_m = rng.standard_normal((H0, H0)).astype(np.float32) * std + mean
    pm = (rng.random((H0, H0)) < 0.3).astype(np.float32)

    state = {}

    @torch.no_grad()
    def preprocess():
        pec = ((pe_m - mean) / std) * pm
        x = np.stack([pec, pm], 0)[None]
        t = torch.from_numpy(x).to(DEV, non_blocking=True)
        t = torch.nn.functional.pad(t, (ph, pad - H0 - ph, ph, pad - H0 - ph))
        state['inp'] = t
        return t

    @torch.no_grad()
    def forward():
        pred, logvar = model(state['inp']).split(1, 1) if False else (None, None)
        out = model(state['inp'])
        state['out'] = out
        return out

    @torch.no_grad()
    def uncertainty():
        pred, sigma = nll_predict(model, state['inp'], True)
        state['pred'] = pred; state['sigma'] = sigma
        return sigma

    @torch.no_grad()
    def compose():
        pred = state['pred'][0, 0, ph:ph + H0, ph:ph + H0] * std + mean
        m = torch.from_numpy(pm).to(DEV)
        pe = torch.from_numpy(pe_m).to(DEV)
        comp = torch.where(m > 0.5, pe, pred)
        return comp.detach().cpu().numpy()

    # warm the graph
    preprocess(); forward(); uncertainty()

    t_pre = timed(preprocess, args.iters, args.warmup)
    t_fwd = timed(forward, args.iters, args.warmup)
    t_unc = timed(uncertainty, args.iters, args.warmup)      # forward + sigma (single pass)
    t_cmp = timed(compose, args.iters, args.warmup)
    total = t_pre + t_unc + t_cmp                            # preprocess + (fwd+sigma) + compose

    res = dict(device=gpu, iters=args.iters, batch=1, dtype='fp32',
               preprocess_ms=t_pre, forward_ms=t_fwd, forward_sigma_ms=t_unc,
               compose_ms=t_cmp, end_to_end_ms=total)
    json.dump(res, open(OUT / 'latency.json', 'w'), indent=2)

    with open(OUT / 'table_latency.tex', 'w') as f:
        f.write('% Auto-generated by tools/latency_e2e.py\n')
        f.write(f'% {gpu}, batch 1, FP32, median of {args.iters} runs.\n')
        f.write('\\begin{tabular}{lr}\n\\toprule\n')
        f.write('Stage & Time [ms] \\\\\n\\midrule\n')
        f.write(f'Input preprocessing (normalise, pad, H2D) & {t_pre:.2f} \\\\\n')
        f.write(f'Network forward ($\\beta$-NLL, incl. $\\hat{{\\sigma}}$) & {t_unc:.2f} \\\\\n')
        f.write(f'Output composition (denormalise, blend, D2H) & {t_cmp:.2f} \\\\\n')
        f.write('\\midrule\n')
        f.write(f'End-to-end (single pass) & {total:.2f} \\\\\n')
        f.write('\\bottomrule\n\\end{tabular}\n')

    print(f'device={gpu}')
    print(f'preprocess {t_pre:.2f} | forward {t_fwd:.2f} | forward+sigma {t_unc:.2f} | '
          f'compose {t_cmp:.2f} | END-TO-END {total:.2f} ms')
    print('(rasterisation front-end and embedded HW: out of scope / future work)')


if __name__ == '__main__':
    main()
