#!/usr/bin/env python3
"""
Compare finished CV experiments (ablations, architectures, …) side by side.

Reads summary/summary.json of each experiment and builds a comparison of the
cross-fold TEST metrics (mean ± std over the 5 folds) as CSV + LaTeX + stdout.

Usage:
    python scripts/eval/compare_experiments.py runs/cv_abl_* --out reports/ablations
    python scripts/eval/compare_experiments.py runs/cv_unet_x runs/cv_pconv_y \\
        --metrics rmse rmse_hole ssim --split test_nll
"""
import argparse
import json
import sys
from datetime import datetime
from pathlib import Path


from elevcomp.utils import write_csv

DEFAULT_METRICS = ['rmse', 'mae', 'rmse_hole', 'mae_hole', 'ssim']


def main():
    p = argparse.ArgumentParser(description='Compare CV experiments side by side.')
    p.add_argument('exp_dirs', nargs='+',
                   help='experiment directories (summary/summary.json required)')
    p.add_argument('--split', default='test_nll',
                   choices=['train', 'val', 'test_nll', 'test_tta'],
                   help='which split/method to compare (default: test_nll)')
    p.add_argument('--metrics', nargs='+', default=DEFAULT_METRICS)
    p.add_argument('--rowhead', default='Experiment',
                   help='first-column header in the LaTeX table')
    p.add_argument('--bold-best', action='store_true',
                   help='bold the best value per metric column (max for SSIM, '
                        'min otherwise) in the LaTeX table')
    p.add_argument('--labels', nargs='+', default=[], metavar='NAME=LABEL',
                   help="readable row labels for the LaTeX table, e.g. "
                        "abl_aug_none=None 'unet_resnet34=Geometric + ray-cone'. "
                        "Names not listed keep their raw experiment name.")
    p.add_argument('--out', default=str(Path(__file__).resolve().parent.parent
                                        / 'reports' / 'compare_experiments'))
    args = p.parse_args()

    label_map = dict(item.split('=', 1) for item in args.labels)

    experiments = []
    for d in args.exp_dirs:
        d = Path(d)
        summ_path = d / 'summary' / 'summary.json'
        if not summ_path.exists():
            print(f'  skipping {d} — no summary/summary.json '
                  f'(run --stage aggregate first)', file=sys.stderr)
            continue
        s = json.load(open(summ_path))
        exp = json.load(open(d / 'experiment.json'))
        experiments.append({
            'name': s['experiment'],
            'dir': str(d),
            'n_folds': s['n_folds_included'],
            'partial': bool(s.get('missing_folds')),
            'overrides': exp['cv'].get('overrides', {}),
            'cross': s['cross_fold'][args.split],
        })
    if not experiments:
        sys.exit('No comparable experiments found.')

    # ── stdout table ──────────────────────────────────────────────────────────
    name_w = max(len(e['name']) for e in experiments) + 2
    hdr = f'{"experiment":<{name_w}} {"folds":>5} ' + ' '.join(
        f'{m:>16}' for m in args.metrics)
    print(f'\nSplit: {args.split}  (mean ± std over folds)\n')
    print(hdr)
    print('─' * len(hdr))
    rows = []
    for e in experiments:
        cells, row = [], {'experiment': e['name'], 'dir': e['dir'],
                          'n_folds': e['n_folds'],
                          'overrides': json.dumps(e['overrides'])}
        for m in args.metrics:
            c = e['cross'].get(m, {})
            mu, sd = c.get('mean_over_folds'), c.get('std_over_folds')
            cells.append(f'{mu:.3f} ± {sd:.3f}' if mu is not None else 'n/a')
            row[m], row[f'{m}_std'] = mu, sd
        flag = ' *PARTIAL*' if e['partial'] else ''
        print(f'{e["name"]:<{name_w}} {e["n_folds"]:>5} '
              + ' '.join(f'{c:>16}' for c in cells) + flag)
        rows.append(row)

    # ── files ─────────────────────────────────────────────────────────────────
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    write_csv(out_dir / f'compare_{args.split}.csv', rows)

    # Best value per metric column (higher is better for SSIM, lower otherwise).
    best = {}
    if args.bold_best:
        for m in args.metrics:
            vals = [e['cross'].get(m, {}).get('mean_over_folds') for e in experiments]
            vals = [v for v in vals if v is not None]
            if vals:
                best[m] = max(vals) if m == 'ssim' else min(vals)

    note = ' Best per column in bold.' if args.bold_best else ''
    lines = [
        f'% Auto-generated by scripts/eval/compare_experiments.py — split: {args.split}',
        f'% Mean ± std over the 5 leave-one-environment-out folds.{note}',
        r'\begin{tabular}{l' + 'c' * len(args.metrics) + '}',
        r'\toprule',
        f'{args.rowhead} & ' + ' & '.join(m.replace('_', r'\_').upper()
                                          for m in args.metrics) + r' \\',
        r'\midrule',
    ]
    for e in experiments:
        cells = []
        for m in args.metrics:
            c = e['cross'].get(m, {})
            mu, sd = c.get('mean_over_folds'), c.get('std_over_folds')
            if mu is None:
                cells.append('n/a')
                continue
            cell = f'{mu:.3f} $\\pm$ {sd:.3f}'
            if best.get(m) is not None and abs(mu - best[m]) < 1e-9:
                cell = r'\textbf{' + cell + '}'
            cells.append(cell)
        name = label_map.get(e['name'], e['name'].replace('_', r'\_'))
        name += (r'\,*' if e['partial'] else '')
        lines.append(f'{name} & ' + ' & '.join(cells) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}']
    (out_dir / f'compare_{args.split}.tex').write_text('\n'.join(lines) + '\n')

    with open(out_dir / f'compare_{args.split}.json', 'w') as f:
        json.dump({'generated_at': datetime.now().isoformat(timespec='seconds'),
                   'split': args.split, 'metrics': args.metrics,
                   'experiments': experiments}, f, indent=2)
    print(f'\nWritten → {out_dir}/compare_{args.split}.{{csv,tex,json}}')


if __name__ == '__main__':
    main()
