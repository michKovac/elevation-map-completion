#!/usr/bin/env python3
"""
Aggregate the large-sector robustness runs (R1 comment 1).

Reads robustness.json from the 30 deg baseline plus the 45/60/90 deg runs,
averages rmse_removed over folds per (model, width, n_sectors), and writes:
  - large_sectors.csv          tidy per-(model,width,n_sectors) means
  - table_large_sectors.tex    LaTeX table, 1-sector case across widths
  - fig_large_sectors.png      rmse_removed vs width (1 sector), 3 models

Run AFTER runs/experiments_review/r1c1_large_sectors/{w45,w60,w90} finish.
    python tools/aggregate_large_sectors.py
"""
import json
import math
from pathlib import Path
from collections import defaultdict
import statistics as st
from elevcomp.paths import project_root, reports_dir

ROOT = project_root()
OUT = reports_dir() / 'robustness_large_sectors'

# robustness.json sources: (width_deg-hint, path). width is also read from rows.
SOURCES = [
    ROOT / 'reports' / 'abl_robustness' / 'robustness.json',   # 30 deg baseline
    OUT / 'w45' / 'robustness.json',
    OUT / 'w60' / 'robustness.json',
    OUT / 'w90' / 'robustness.json',
]

MODEL_LABEL = {
    'abl_aug_none': 'None',
    'abl_aug_geo':  'Geometric',
    'unet_resnet34': 'Ray-cone',
}
MODEL_ORDER = ['None', 'Geometric', 'Ray-cone']


def load_rows():
    rows = []
    for p in SOURCES:
        if not p.exists():
            print(f'  ! missing (skipped): {p}')
            continue
        d = json.load(open(p))
        rows.extend(d['rows'])
        print(f'  loaded {len(d["rows"]):4d} rows from {p}')
    return rows


def agg(rows):
    # key: (model_label, width, n_sectors) -> list of rmse_removed (fold-level)
    removed = defaultdict(list)
    hole = defaultdict(list)   # rmse_hole (clean reference at n_sectors=0)
    by_fold = defaultdict(dict)  # (model, width, n_sectors) -> {fold: rmse_removed}
    for r in rows:
        lbl = MODEL_LABEL.get(r['model'], r['model'])
        w = int(round(r['width_deg']))
        ns = int(r['n_sectors'])
        v = r.get('rmse_removed')
        if v is not None and isinstance(v, (int, float)) and not math.isnan(v):
            removed[(lbl, w, ns)].append(v)
            by_fold[(lbl, w, ns)][int(r['fold'])] = v
        hv = r.get('rmse_hole')
        if hv is not None and not (isinstance(hv, float) and math.isnan(hv)):
            hole[(lbl, w, ns)].append(hv)
    return removed, hole, by_fold


def paired(by_fold, lbl, w, ns):
    """Per-fold difference None minus lbl at one width. Positive = lbl is better."""
    a = by_fold.get(('None', w, ns), {})
    b = by_fold.get((lbl, w, ns), {})
    folds = sorted(set(a) & set(b))
    return [a[f] - b[f] for f in folds]


def main():
    print('Loading robustness runs...')
    rows = load_rows()
    if not rows:
        print('No data yet. Run the experiment first.')
        return
    removed, hole, by_fold = agg(rows)

    widths = sorted({w for (_, w, _) in removed})
    n_sec = sorted({ns for (_, _, ns) in removed})
    print(f'widths: {widths}   n_sectors: {n_sec}')

    # ---- tidy CSV ----
    csv = OUT / 'large_sectors.csv'
    with open(csv, 'w') as f:
        f.write('model,width_deg,n_sectors,mean_rmse_removed,std_rmse_removed,n_folds\n')
        for lbl in MODEL_ORDER:
            for w in widths:
                for ns in n_sec:
                    vs = removed.get((lbl, w, ns), [])
                    if vs:
                        f.write(f'{lbl},{w},{ns},{st.mean(vs):.4f},'
                                f'{st.pstdev(vs):.4f},{len(vs)}\n')
    print(f'wrote {csv}')

    # ---- LaTeX table: 1-sector case across widths (single-camera blind zone) ----
    NS = 1
    tex = OUT / 'table_large_sectors.tex'
    with open(tex, 'w') as f:
        f.write('% Auto-generated by tools/aggregate_large_sectors.py\n')
        f.write('% RMSE on removed cells [m], mean over 5 folds, one sector of the given width.\n')
        f.write('\\begin{tabular}{lcccc}\n\\toprule\n')
        f.write('Augmentation & 30$^\\circ$ & 45$^\\circ$ & 60$^\\circ$ & 90$^\\circ$ \\\\\n\\midrule\n')
        for lbl in MODEL_ORDER:
            cells = []
            for w in [30, 45, 60, 90]:
                vs = removed.get((lbl, w, NS), [])
                cells.append(f'{st.mean(vs):.2f} $\\pm$ {st.pstdev(vs):.2f}' if vs else '--')
            f.write(f'{lbl} & ' + ' & '.join(cells) + ' \\\\\n')
        # relative improvement of Ray-cone vs None
        f.write('\\midrule\n')
        imp = []
        for w in [30, 45, 60, 90]:
            n = removed.get(('None', w, NS), [])
            r = removed.get(('Ray-cone', w, NS), [])
            if n and r:
                imp.append(f'{100*(st.mean(n)-st.mean(r))/st.mean(n):.1f}\\%')
            else:
                imp.append('--')
        f.write('Ray-cone vs None & ' + ' & '.join(imp) + ' \\\\\n')
        f.write('\\bottomrule\n\\end{tabular}\n')
    print(f'wrote {tex}')

    # ---- figure ----
    # Panel (a) shows the absolute error, panel (b) the per-fold paired difference
    # against no augmentation. The spread across folds is the spread across test
    # environments (about 1.3 m) and it dwarfs the effect, so error bars on the
    # absolute curves would hide a difference that holds in every single fold.
    # The paired view removes that environment offset and is the honest test.
    try:
        import matplotlib
        matplotlib.use('Agg')
        import matplotlib.pyplot as plt
        STYLE = {'None': ('-', 'o'), 'Geometric': ('--', 's'), 'Ray-cone': (':', '^')}
        WIDTHS = [30, 45, 60, 90]
        fig, ax = plt.subplots(1, 2, figsize=(9.2, 3.5))

        ax[0].axvspan(5, 25, alpha=0.15, color='0.8', label='training range')
        for lbl in MODEL_ORDER:
            xs, ys = [], []
            for w in WIDTHS:
                vs = removed.get((lbl, w, NS), [])
                if vs:
                    xs.append(w); ys.append(st.mean(vs))
            if xs:
                ls, mk = STYLE.get(lbl, ('-', 'o'))
                ax[0].plot(xs, ys, color='black', linestyle=ls, marker=mk,
                           markersize=7, linewidth=1.8, markerfacecolor='white',
                           label=lbl)
        ax[0].set_xlabel('Sector width [deg] (one removed sector)')
        ax[0].set_ylabel('RMSE on removed cells [m]')
        ax[0].set_title('(a) mean over folds', fontsize=10)
        ax[0].legend(fontsize=8)

        ax[1].axhline(0.0, color='black', linewidth=1.0)
        for lbl in ['Geometric', 'Ray-cone']:
            xs, ys, es = [], [], []
            for w in WIDTHS:
                d = paired(by_fold, lbl, w, NS)
                if d:
                    xs.append(w); ys.append(st.mean(d))
                    es.append(st.pstdev(d) if len(d) > 1 else 0.0)
            if xs:
                ls, mk = STYLE.get(lbl, ('-', 'o'))
                ax[1].errorbar(xs, ys, yerr=es, color='black', linestyle=ls,
                               marker=mk, markersize=7, linewidth=1.8,
                               markerfacecolor='white', capsize=3, label=lbl)
        ax[1].set_xlabel('Sector width [deg] (one removed sector)')
        ax[1].set_ylabel('RMSE reduction vs no augmentation [m]')
        ax[1].set_title('(b) per-fold paired difference', fontsize=10)
        ax[1].legend(fontsize=8)
        for a in ax:
            a.grid(True, color='0.9', linewidth=0.6)
            a.set_axisbelow(True)
        plt.tight_layout()
        fig_path = OUT / 'fig_large_sectors.png'
        plt.savefig(fig_path, dpi=300)
        plt.close(fig)
        print(f'wrote {fig_path}')
    except Exception as e:
        print(f'figure skipped: {e}')

    # ---- paired summary (what panel (b) shows) ----
    print('\n=== paired per-fold reduction vs no augmentation [m] (1 sector) ===')
    for lbl in ['Geometric', 'Ray-cone']:
        for w in [30, 45, 60, 90]:
            d = paired(by_fold, lbl, w, NS)
            if d:
                print(f'  {lbl:10s} {w:>3}deg  {st.mean(d):+.3f} +/- {st.pstdev(d):.3f}'
                      f'   better in {sum(x > 0 for x in d)}/{len(d)} folds')

    # ---- console summary ----
    print('\n=== 1-sector RMSE on removed cells [m] (mean over folds) ===')
    print(f'{"width":>6} | ' + ' '.join(f'{m:>10}' for m in MODEL_ORDER))
    for w in [30, 45, 60, 90]:
        vals = []
        for lbl in MODEL_ORDER:
            vs = removed.get((lbl, w, NS), [])
            vals.append(f'{st.mean(vs):.3f}' if vs else '--')
        print(f'{w:>5}\u00b0 | ' + ' '.join(f'{v:>10}' for v in vals))


if __name__ == '__main__':
    main()
